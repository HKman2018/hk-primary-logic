"""Write js/vocab-data.js from the Google Translate zh-TW word list.

From the repo root:

    python3 assets/vocab/generate_vocab_data.py

Source of truth:
    assets/vocab/wordlist-gt-201.json
    assets/vocab/wordlist-gt-201.csv

The quiz loads the generated file. Each row is one unique English lemma
plus its Traditional Chinese gloss. The script does not emit image paths
or zhCue flags. Do not hand-edit js/vocab-data.js.
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
JSON_PATH = HERE / "wordlist-gt-201.json"
CSV_PATH = HERE / "wordlist-gt-201.csv"
DATA_JS = ROOT / "js" / "vocab-data.js"
EXPECTED = 201


def load_csv():
    with CSV_PATH.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def load_json():
    return json.loads(JSON_PATH.read_text(encoding="utf-8"))


def normalize_row(row, source):
    if "id" not in row or "english" not in row or "zh" not in row:
        raise SystemExit("%s row missing id/english/zh: %r" % (source, row))
    try:
        scene_id = int(row["id"])
    except (TypeError, ValueError):
        raise SystemExit("%s bad id: %r" % (source, row.get("id")))
    english = row["english"]
    zh = row["zh"]
    if not isinstance(english, str) or not english.strip():
        raise SystemExit("%s empty english for id %s" % (source, scene_id))
    if not isinstance(zh, str) or not zh.strip():
        raise SystemExit("%s empty zh for id %s" % (source, scene_id))
    if english != english.strip() or zh != zh.strip():
        raise SystemExit("%s untrimmed text for id %s" % (source, scene_id))
    return {"id": scene_id, "english": english, "zh": zh}


def main():
    json_rows = [normalize_row(row, "json") for row in load_json()]
    csv_rows = [normalize_row(row, "csv") for row in load_csv()]
    if json_rows != csv_rows:
        raise SystemExit("csv and json word lists differ")
    if len(json_rows) != EXPECTED:
        raise SystemExit("expected %s rows, got %s" % (EXPECTED, len(json_rows)))
    ids = [row["id"] for row in json_rows]
    if ids != list(range(1, EXPECTED + 1)):
        raise SystemExit("ids must be 1..%s in order" % EXPECTED)
    folded = [row["english"].lower() for row in json_rows]
    if len(set(folded)) != EXPECTED:
        raise SystemExit("english values are not unique case-insensitively")
    lines = [
        "/** 「看圖學英文」word bank. Independent of LOGIC_BANK and the daily pool.",
        " *  Google Translate Traditional Chinese (zh-TW), 201 unique English lemmas.",
        " *  The quiz shows「意思：{zh}」and accepts only the English answer",
        " *  (trim + toLowerCase). Rows have no picture path and no picture-cue flag.",
        " *  Generated by assets/vocab/generate_vocab_data.py from",
        " *  assets/vocab/wordlist-gt-201.json. Do not edit by hand.",
        " */",
        "window.VOCAB_PICTURE_BANK = [",
    ]
    for row in json_rows:
        lines.append(
            "  { id: %s, answer: %s, zh: %s },"
            % (
                json.dumps("w%03d" % row["id"], ensure_ascii=False),
                json.dumps(row["english"], ensure_ascii=False),
                json.dumps(row["zh"], ensure_ascii=False),
            )
        )
    lines.append("];")
    lines.append("")
    DATA_JS.write_text("\n".join(lines), encoding="utf-8")
    print("wrote %s unique english rows to %s" % (len(json_rows), DATA_JS.relative_to(ROOT)))


if __name__ == "__main__":
    main()
